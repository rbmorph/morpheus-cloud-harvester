package com.hpe.morpheus.harvester.plugin.sync

import com.hpe.morpheus.harvester.plugin.HpeHarvesterClusterProvider
import com.hpe.morpheus.harvester.plugin.HpeHarvesterPlugin
import com.hpe.morpheus.harvester.plugin.apihelper.NodeApiHelper
import com.hpe.morpheus.harvester.plugin.utils.HarvesterConstants
import com.morpheusdata.core.MorpheusContext
import com.morpheusdata.core.data.DataFilter
import com.morpheusdata.core.data.DataOrFilter
import com.morpheusdata.core.data.DataQuery
import com.morpheusdata.core.util.SyncTask
import com.morpheusdata.model.*
import com.morpheusdata.model.projection.ComputeServerIdentityProjection
import groovy.util.logging.Slf4j
import io.reactivex.rxjava3.core.Observable

/**
 * Synchronizes Harvester cluster nodes with Morpheus ComputeServer entities
 * Purpose: Discovers and manages Harvester cluster nodes as compute servers
 * Author: Generated by GitHub Copilot
 * Date: August 25, 2025
 */
@Slf4j
class NodesSync {

    private ComputeServerGroup cluster
    private MorpheusContext morpheusContext
    private HpeHarvesterPlugin plugin

    public NodesSync(HpeHarvesterPlugin plugin, ComputeServerGroup cluster) {
        this.plugin = plugin
        this.cluster = cluster
        this.morpheusContext = plugin.morpheusContext
    }

    def execute() {
        log.debug "Harvester: execute NodesSync: ${cluster}"
        try {
            Cloud cloud = cluster.cloud
            NodeApiHelper nodeApiHelper = new NodeApiHelper(cluster)
            def cloudNodes = nodeApiHelper.getNodes()
            log.info("Harvester: NodesSync cloudNodes# ${cloudNodes.nodes?.size()}")

            if(cloudNodes.success == true) {
                if (hostServerGroup() == null) {
                    removeHostsWithGuestOs(cloud)
                }
                Observable domainRecords = morpheusContext.async.computeServer.listIdentityProjections(
                        new DataQuery().withFilters(
                                new DataFilter('cloud', cloud),
                                // by category: hosts synced by earlier versions were 'morpheus-node' servers of the cluster
                                new DataFilter('category', "${HarvesterConstants.CATEGORY_HARVESTER_NODE_PREFIX}${cluster.id}".toString()),
                        )
                )

                SyncTask<ComputeServerIdentityProjection, Map, ComputeServer> syncTask = new SyncTask<>(domainRecords, cloudNodes.nodes ?: [])
                syncTask.addMatchFunction { ComputeServerIdentityProjection domainObject, Map apiItem ->
                    domainObject.externalId == apiItem.uid
                }.onDelete { removeItems ->
                    removeNodes(removeItems)
                }.onUpdate { List<SyncTask.UpdateItem<ComputeServer, Map>> updateItems ->
                    updateNodes(updateItems)
                }.onAdd { itemsToAdd ->
                    addNodes(itemsToAdd)
                }.withLoadObjectDetailsFromFinder { updateItems ->
                    return morpheusContext.async.computeServer.list(
                            new DataQuery().withFilters(
                                    new DataOrFilter(updateItems.collect {new DataFilter('id', it.existingItem.id) })
                            ))
                }.start()

            } else {
                log.error("Harvester: Error retrieving nodes ${cloudNodes.message}")
                throw new Exception("Error retrieving nodes for ${this.cluster.name}")
            }

        } catch(e) {
            log.error("Harvester: NodesSync error: ${e}", e)
        }
    }

    private addNodes(addList) {
        log.info("Harvester: Nodes addList# ${addList?.size()}")
        def itemsToAdd = []
        Long sockets = socketsPerHost()

        addList?.each { Map nodeToAdd ->
            try {
                def license = true
                if(license) {
                    def ipAddress = nodeToAdd.internalIP ?: nodeToAdd.externalIP ?: HarvesterConstants.DEFAULT_IP
                    def hostname = nodeToAdd.hostname ?: nodeToAdd.name

                    // Dynamically determine server type based on node type
                    def serverTypeCode = getServerTypeCode(nodeToAdd.nodeType)
                    log.info("Harvester: serverTypeCode: ${serverTypeCode}")
                    ComputeServerType serverType = morpheusContext.async.cloud.
                            findComputeServerTypeByCode(serverTypeCode).blockingGet()

                    def nodeConfig = [
                            account      : cluster.owner,
                            externalId   : nodeToAdd.uid,
                            uniqueId     : nodeToAdd.uid,
                            name         : nodeToAdd.name,
                            externalIp   : nodeToAdd.externalIP ?: ipAddress,
                            internalIp   : nodeToAdd.internalIP ?: ipAddress,
                            sshHost      : ipAddress,
                            sshUsername  : HarvesterConstants.SSH_USER_ROOT,
                            hostname     : hostname,
                            provision    : false,
                            computeServerType: serverType,
                            cloud        : cluster.cloud,
                            category     : "${HarvesterConstants.CATEGORY_HARVESTER_NODE_PREFIX}${cluster.id}",
                            managed      : false,
                            discovered   : true,
                            serverType   : HarvesterConstants.SERVER_TYPE_HYPERVISOR,
                            status       : HarvesterConstants.STATUS_PROVISIONED,
                            serverGroup  : hostServerGroup(),
                    ]

                    def poweredOn = nodeToAdd.ready == true
                    nodeConfig.powerState = poweredOn ? HarvesterConstants.POWER_ON : HarvesterConstants.POWER_OFF
                    nodeConfig.apiKey = UUID.randomUUID()
                    log.info("Harvester: poweredOn: ${nodeConfig.powerState}")

                    ComputeServer computeServer = new ComputeServer(nodeConfig)
                    computeServer.serverGroup = hostServerGroup()
                    def rawData = [
                            status: nodeToAdd.status,
                            kind: "Harvester",
                            apiVersion: "",
                    ]
                    computeServer.rawData =  rawData.encodeAsJSON().toString()
                    def maxCores = nodeToAdd.cpuCapacity ?: 0
                    def maxMemory = nodeToAdd.memoryCapacity ?: 0
                    def maxStorage = nodeToAdd.storageCapacity ?: 0

                    computeServer.maxMemory = maxMemory
                    computeServer.maxCores = maxCores
                    // physical CPUs (sockets): maxCpu is the CPU count field in the 1.3 plugin API
                    computeServer.maxCpu = sockets
                    computeServer.coresPerSocket = coresPerSocket(maxCores, sockets)
                    computeServer.maxStorage = maxStorage
                    computeServer.usedCpu = nodeToAdd.cpuUsage ?: 0
                    computeServer.usedMemory = nodeToAdd.memoryUsage ?: 0

                    // Set OS type based on node OS
                    def osTypeCode = mapNodeOsType(nodeToAdd.status?.nodeInfo?.operatingSystem)
                    OsType osType = morpheusContext.services.osType.find(
                            new DataQuery().withFilter('code', osTypeCode ?: HarvesterConstants.OS_TYPE_LINUX))
                    // A hypervisor host of a Harvester cloud has no guest OS record: with one,
                    // Morpheus counts the host as a Linux workload
                    computeServer.serverOs = hostServerGroup() == null ? null : osType
                    computeServer.osType = osType?.platform?.toString() ?: HarvesterConstants.OS_TYPE_LINUX
                    log.info("Harvester: Adding Node with osTypeCode: ${osTypeCode}, osType: ${computeServer.osType}")

                    computeServer.capacityInfo = new ComputeCapacityInfo(
                            maxCores: maxCores, maxMemory: maxMemory,
                            maxStorage: maxStorage, usedStorage: 0,
                            usedCores: nodeToAdd.cpuUsage, usedMemory: nodeToAdd.memoryUsage)

                    itemsToAdd << computeServer
                }
            }
            catch (t) {
                log.error("Error adding node ${nodeToAdd.name}: ${t.message}", t)
            }
        }

        if(itemsToAdd) {
            morpheusContext.services.computeServer.bulkCreate(itemsToAdd)
            log.info "Harvester: successfully added Nodes# ${itemsToAdd.size()}"
        }
    }

    private updateNodes(updateList) {
        log.info("Harvester: Nodes matchList# ${updateList?.size()}")
        Long sockets = socketsPerHost()

        def itemsToUpdate = []
        updateList?.each { updateMap ->
            try {
                ComputeServer server = updateMap.existingItem
                Map matchedNode = updateMap.masterItem
                log.debug("Harvester: Checking state of matched node ${matchedNode.name} - ${server}")

                if (server && server.status != 'provisioning') {
                    def hostname = matchedNode.hostname ?: matchedNode.name

                    ComputeServer.PowerState powerState = matchedNode.ready == true ? ComputeServer.PowerState.on : ComputeServer.PowerState.off

                    // Use local methods for server type and OS type
                    def serverTypeCode = getServerTypeCode(matchedNode.nodeType)
                    ComputeServerType serverType = morpheusContext.async.cloud.
                            findComputeServerTypeByCode(serverTypeCode).blockingGet()

                    // Use pre-processed resource values
                    def maxCores = matchedNode.cpuCapacity ?: 0
                    def maxMemory = matchedNode.memoryCapacity ?: 0
                    def maxStorage = matchedNode.storageCapacity ?: 0
                    def usedCpu = matchedNode.cpuUsage ?: 0
                    def usedMemory = matchedNode.memoryUsage ?: 0

                    // Use local method for OS type
                    def osTypeCode = mapNodeOsType(matchedNode.status?.nodeInfo?.operatingSystem)
                    OsType osType = morpheusContext.services.osType.find(
                            new DataQuery().withFilter('code', osTypeCode ?: HarvesterConstants.OS_TYPE_LINUX))

                    def save = false

                    // uncomment once rawData field is added to ComputeServer
                    def rawDataConfig = [
                            status: matchedNode.status,
                            kind: "Harvester",
                            apiVersion: "",
                    ]
                    def rawData = rawDataConfig.encodeAsJSON().toString()
                    if (server.rawData != rawData) {
                        server.rawData = rawData
                        save = true
                    }

                    if (hostServerGroup() == null) {
                        // hypervisor host of a Harvester cloud: no guest OS record (see addNodes)
                        if (server.serverOs != null) {
                            server.serverOs = null
                            save = true
                        }
                        if (server.osType != HarvesterConstants.OS_TYPE_LINUX) {
                            server.osType = HarvesterConstants.OS_TYPE_LINUX
                            save = true
                        }
                    } else if (!server.sourceImage && server.serverOs?.code != osType?.code) {
                        server.serverOs = osType
                        server.osType = osType?.platform?.toString() ?: HarvesterConstants.OS_TYPE_LINUX
                        save = true
                    }

                    if (server.computeServerType?.code != serverType?.code) {
                        server.computeServerType = serverType
                        save = true
                    }

                    if (server.powerState != powerState) {
                        log.info("Harvester: Updating Node: ${hostname} to" +
                                " powerState: ${powerState} from ${server.powerState}")
                        server.powerState = powerState
                        save = true
                    }

                    if (server.hostname != hostname) {
                        server.hostname = hostname
                        save = true
                    }

                    if (server.name != matchedNode.name) {
                        server.name = matchedNode.name
                        save = true
                    }

                    def capacityInfo = server.capacityInfo
                    if(!capacityInfo) {
                        server.capacityInfo = new ComputeCapacityInfo(
                                maxCores:maxCores, maxMemory:maxMemory,
                                maxStorage: maxStorage,
                                usedMemory: usedMemory, usedCores: usedCpu)
                        capacityInfo = server.capacityInfo
                        save = true
                    }

                    if (server.usedCpu != usedCpu) {
                        server.usedCpu = usedCpu
                        capacityInfo.usedCores = usedCpu
                        save = true
                    }

                    if (server.usedMemory != usedMemory) {
                        server.usedMemory = usedMemory
                        capacityInfo.usedMemory = usedMemory
                        save = true
                    }

                    if (server.maxMemory != maxMemory) {
                        server.maxMemory = maxMemory
                        capacityInfo.maxMemory = maxMemory
                        save = true
                    }

                    if (server.maxCores != maxCores) {
                        server.maxCores = maxCores
                        capacityInfo.maxCores = maxCores
                        save = true
                    }

                    // VM hypervisor host (earlier versions synced Kubernetes-style nodes)
                    if (server.serverType != HarvesterConstants.SERVER_TYPE_HYPERVISOR) {
                        server.serverType = HarvesterConstants.SERVER_TYPE_HYPERVISOR
                        save = true
                    }
                    if (server.provision != false) {
                        server.provision = false
                        save = true
                    }
                    if (hostServerGroup() == null && server.serverGroup != null) {
                        server.serverGroup = null
                        save = true
                    }
                    Long hostCoresPerSocket = coresPerSocket(maxCores, sockets)
                    if (server.maxCpu != sockets) {
                        server.maxCpu = sockets
                        save = true
                    }
                    if (server.coresPerSocket != hostCoresPerSocket) {
                        server.coresPerSocket = hostCoresPerSocket
                        save = true
                    }

                    if (server.maxStorage != maxStorage) {
                        server.maxStorage = maxStorage
                        capacityInfo.maxStorage = maxStorage
                        save = true
                    }

                    if (save) {
                        itemsToUpdate << server
                    }
                }
            }
            catch (t) {
                log.error("Error updating node: ${t.message}", t)
            }
        }
        if (itemsToUpdate) {
            log.info("Harvester: updating Nodes # ${itemsToUpdate?.size()}")
            morpheusContext.async.computeServer.bulkSave(itemsToUpdate).blockingGet()
        }
    }

    /**
     * Hosts of a Harvester cloud belong to the cloud, not to the connection record.
     * Clusters added with earlier versions keep the link.
     */
    ComputeServerGroup hostServerGroup() {
        return HpeHarvesterClusterProvider.isCloudManaged(cluster) ? null : cluster
    }

    /**
     * Physical sockets per host from the cloud's "Sockets per Host" setting (Harvester's API has no socket count).
     */
    Long socketsPerHost() {
        try {
            Cloud cloud = cluster.cloud
            if (cloud?.id && cloud.getConfigProperty(HarvesterConstants.CONFIG_SOCKETS_PER_HOST) == null) {
                cloud = morpheusContext.services.cloud.get(cloud.id) ?: cloud
            }
            return parseSockets(cloud?.getConfigProperty(HarvesterConstants.CONFIG_SOCKETS_PER_HOST))
        } catch (Exception e) {
            log.warn("Harvester: unable to read Sockets per Host, using 1: ${e.message}")
            return 1L
        }
    }

    static Long parseSockets(def value) {
        try {
            Long sockets = value?.toString()?.trim() ? value.toString().trim().toBigDecimal().toLong() : 1L
            return sockets > 0 ? sockets : 1L
        } catch (Exception ignored) {
            return 1L
        }
    }

    static Long coresPerSocket(def maxCores, Long sockets) {
        Long cores = (maxCores ?: 0) as Long
        Long perSocket = sockets ? (cores / sockets) as Long : cores
        return perSocket > 0 ? perSocket : 1L
    }

    /**
     * Hosts synced by earlier versions carry a guest OS record ('linux'), which makes Morpheus count them as Linux
     * workloads instead of hypervisor hosts. Morpheus ignores a save that clears it, so such hosts are removed here
     * and re-added by this sync without one (VMs are re-linked to them by the VM sync that follows).
     */
    void removeHostsWithGuestOs(Cloud cloud) {
        try {
            List<ComputeServer> hosts = morpheusContext.services.computeServer.list(new DataQuery().withFilters(
                    new DataFilter('cloud', cloud),
                    new DataFilter('category', "${HarvesterConstants.CATEGORY_HARVESTER_NODE_PREFIX}${cluster.id}".toString())
            )) ?: []
            List<ComputeServer> withOs = hosts.findAll { it.serverOs != null }
            if (withOs) {
                log.info("Harvester: re-creating hosts with a guest OS record so they count as hypervisor hosts: ${withOs*.name}")
                morpheusContext.async.computeServer.bulkRemove(withOs).blockingGet()
            }
        } catch (Exception e) {
            log.warn("Harvester: unable to re-create hosts with a guest OS record: ${e.message}")
        }
    }

    private removeNodes(removeList) {
        log.info("Harvester: Nodes removeList# ${removeList?.size()}")
        morpheusContext.async.computeServer.bulkRemove(removeList).blockingGet()
        log.info("Harvester: successfully removed Nodes# ${removeList?.size()}")
    }

    /**
     * Helper method to map Harvester node OS type to Morpheus OS type
     */
    private static String mapNodeOsType(Object osTypeObj) {
        if (!osTypeObj) return HarvesterConstants.OS_TYPE_LINUX
        String osType = osTypeObj.toString().toLowerCase()

        switch(osType) {
            case HarvesterConstants.OS_TYPE_LINUX:
                return HarvesterConstants.OS_TYPE_LINUX
            case HarvesterConstants.OS_TYPE_WINDOWS:
                return HarvesterConstants.OS_TYPE_WINDOWS
            default:
                return HarvesterConstants.OS_TYPE_LINUX
        }
    }

    /**
     * Helper method to determine the appropriate ComputeServerType code based on Harvester node type
     */
    private static String getServerTypeCode(Object nodeTypeObj) {
        if (!nodeTypeObj) return HarvesterConstants.SERVER_TYPE_HARVESTER_WORKER
        String nodeType = nodeTypeObj.toString().toLowerCase()

        switch(nodeType) {
            case 'master':
            case 'control-plane':
                return HarvesterConstants.SERVER_TYPE_HARVESTER_MASTER
            case 'worker':
                return HarvesterConstants.SERVER_TYPE_HARVESTER_WORKER
            case 'infra':
            case 'infrastructure':
                return HarvesterConstants.SERVER_TYPE_HARVESTER_WORKER  // Treat infra nodes as workers
            default:
                return HarvesterConstants.SERVER_TYPE_HARVESTER_WORKER  // Default to worker
        }
    }
}
