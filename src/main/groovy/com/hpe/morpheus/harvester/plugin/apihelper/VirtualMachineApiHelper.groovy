    // Fetch DataVolumes and create a cache mapping of namespace:name to details
    def getDataVolumeCache(){
        DataVolumeApiHelper dvHelper = new DataVolumeApiHelper(serverGroup)
        def dvResult = dvHelper.getDataVolumes()
        def dataVolumes = dvResult.success ? dvResult.datavolumes : []
