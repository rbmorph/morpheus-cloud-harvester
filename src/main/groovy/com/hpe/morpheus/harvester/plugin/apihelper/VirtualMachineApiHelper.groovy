    def getVMs(Map<String, StorageVolumeType> storageVolumeTypeMap, Map<String, StorageControllerType> storageControllerTypeMap) {
        def ret = [success: true, vms: []]

        try {
            // Fetch PVCs first to cache storage class and size information
            PVCApiHelper pvcHelper = new PVCApiHelper(serverGroup)
            def pvcResult = pvcHelper.getPVCs(true)
            def pvcCache = pvcResult.success ? pvcResult.namespacePVCMap : [:]

            // Fetch DataVolumes to cache storage class and size information
            def dataVolumeCache = getDataVolumeCache()

            // Fetch nodes for node details lookup
            NodeApiHelper nodeHelper = new NodeApiHelper(serverGroup)
            def nodesResult = nodeHelper.getNodes()
            def nodesCache = [:]
            if (nodesResult.success) {
                nodesResult.nodes.each { node ->
                    nodesCache[node.name] = node
                }
            }

            // Fetch VMs and VM instances
            ServiceResponse vmsResponse = apiClient.get(HarvesterConstants.HARVESTER_API_V1_VMS)
            ServiceResponse vmInstancesResponse = apiClient.get(HarvesterConstants.HARVESTER_API_V1_VM_INSTANCES)

            if (vmsResponse.success) {
                def vms = vmsResponse.data?.items ?: []
                def vmInstances = vmInstancesResponse.success ? (vmInstancesResponse.data?.items ?: []) : []

                // Create a map of running VM instances for quick lookup
                Map<String, Object> runningVMInstances = [:]
                vmInstances.each { vmInstance ->
                    String key = "${vmInstance.metadata.namespace}:${vmInstance.metadata.name}"
                    runningVMInstances[key] = vmInstance
                }

                vms.each { vm ->
                    String vmNamespace = vm.metadata.namespace
                    String vmName = vm.metadata.name

                    // Skip VMs that have the provisioning label (being provisioned by Morpheus)
                    if (isProvisioningVM(vm.metadata?.labels)) {
                        log.info("Skipping VM: ${vmName} in namespace: ${vmNamespace}, it has provisioning label, labels: ${vm.metadata?.labels}")
                        return // continue to next VM
                    }

                    // Filter out system namespaces
                    if (!CommonApiHelper.isSystemNamespace(vmNamespace)) {
                        String vmKey = "${vmNamespace}:${vmName}"
                        def vmInstance = runningVMInstances[vmKey]

                        def vmData = [
                            uid: vm.metadata.uid,
                            name: vmName,
                            namespace: vmNamespace,
                            status: vm.status?.printableStatus ?: 'Unknown',
                            isRunning: vmInstance != null,
                            createdAt: vm.metadata.creationTimestamp,
                            labels: vm.metadata?.labels ?: [:],
                            hotplug: CpuTopology.isHotplugEnabled(vm as Map),
                            nodeName: null,
                            nodeDetails: null
                        ]

                        // Extract node details from running VM instance
                        if (vmInstance?.status?.nodeName) {
                            vmData.nodeName = vmInstance.status.nodeName
                            // Get detailed node information from cache
                            def nodeDetails = nodesCache[vmData.nodeName]
                            if (nodeDetails) {
                                vmData.nodeDetails = [
                                    uid: nodeDetails.uid,
                                    name: nodeDetails.name,
                                    nodeType: nodeDetails.nodeType,
                                ]
                            }
                        }

                        // Extract CPU and Memory from VM domain specification
                        if (vm.spec?.template?.spec?.domain) {
                            def domain = vm.spec.template.spec.domain
                            vmData.cpu = extractCpuInfo(domain)
                            vmData.memory = extractMemoryInfo(domain)
                        } else {
                            // Fallback: try to extract from running instance if available
                            if (vmInstance?.status?.guestOSInfo) {
                                // Try to get CPU/memory from guest OS info if available
                                vmData.cpu = [
                                    cores: vmInstance.status.guestOSInfo.cpuCount ?: 0,
                                    sockets: 1,
                                    threads: 1
                                ]
                                vmData.memory = vmInstance.status.guestOSInfo.memorySize ?: 0L
                            } else {
                                // Default values when no resource information is available
                                vmData.cpu = [cores: 0, sockets: 1, threads: 1]
                                vmData.memory = 0L
                            }
                        }

                        // Extract OS type from VM template metadata annotations
                        def osType = extractOsType(vmName, vm.spec)
                        vmData.osType = osType

                        // Extract volumes and storage classes using utility method - now includes dataVolumeTemplates and PVC cache
                        def volumes = extractVolumeInfo(
                            osType,
                            vm.spec?.template?.spec?.volumes,
                            vm.spec?.dataVolumeTemplates,
                            vmNamespace,
                            pvcCache,
                            vm.spec?.template?.spec?.domain?.devices?.disks,
                            dataVolumeCache
                        )
                        vmData.volumes = filterVolumes(volumes, vmName, storageVolumeTypeMap, storageControllerTypeMap)


                        // Extract network interfaces - prioritize running instance data
                        if (vmInstance) {
                            vmData.interfaces = extractNetworkInterfacesFromSpecAndStatus(vmInstance.status?.interfaces,
                                    vmInstance.spec?.domain?.devices?.interfaces,vmInstance.spec?.networks)
                            // Update status from running instance if available
                           // vmData.status = vmInstance.status?.phase ?: vmData.status
                        } else {
                            // Extract from VM spec if no running instance
                            vmData.interfaces = extractNetworkInterfacesFromSpec(vm.spec?.template?.spec?.networks, vm.spec?.template?.spec?.domain?.devices?.interfaces)
                        }

                        log.debug("VM: ${vmName}, details: ${vmData}")
                        ret.vms << vmData
                    } else{
                        log.warn("Skipping VM:${vmName}, its in system namespace: ${vmNamespace}")
                    }
                }

                ret.success = true
                log.info("Fetched ${ret.vms.size()} VMs from Harvester")
            } else {
                log.error("Failed to fetch VMs from Harvester: ${vmsResponse.msg}, errorCode:${vmsResponse.errorCode}")
                ret.success = false
                ret.message = vmsResponse.msg ?: 'Failed to fetch VMs from Harvester'
            }
        } catch (Exception e) {
            log.error("Error fetching VMs from Harvester", e)
            ret.success = false
            ret.message = "Error fetching VMs: ${e.message}"
        }

        return ret
    }

    /**
     * Check if VM has the provisioning label in its metadata with value 'true'
     * VMs with this label are being provisioned by Morpheus and should be skipped during sync
     * @param labels Map of VM metadata labels
     * @return true if VM has the provisioning label set to 'true', false otherwise
     */
    static Boolean isProvisioningVM(Map labels) {
        if (!labels || !labels.containsKey(HarvesterConstants.MORPHEUS_PROVISIONING_LABEL)) {
            return false
        }
        return labels[HarvesterConstants.MORPHEUS_PROVISIONING_LABEL] == "true"
    }

    /**
     * Extract CPU information from VM domain specification
     * @param domain The VM domain specification
     * @return Map containing CPU cores, sockets, and threads information
     */
    static extractCpuInfo(domain) {
        def cpuInfo = [cores: 0, sockets: 1, threads: 1]

        if (domain?.cpu) {
            // Extract from domain.cpu specification
            cpuInfo.cores = domain.cpu.cores ?: 0
            cpuInfo.sockets = domain.cpu.sockets ?: 1
            cpuInfo.threads = domain.cpu.threads ?: 1
        } else if (domain?.resources) {
            // Fallback: try to get from resources
            def resources = domain.resources
            if (resources.requests?.cpu) {
                cpuInfo.cores = CommonParser.parseCpuValue(resources.requests.cpu)
            } else if (resources.limits?.cpu) {
                cpuInfo.cores = CommonParser.parseCpuValue(resources.limits.cpu)
            }
        }

        return cpuInfo
    }

    /**
     * Extract memory information from VM domain specification
     * @param domain The VM domain specification
     * @return Memory size in bytes
     */
    static extractMemoryInfo(domain) {
        // CPU and memory hot add: the limits hold the maximum, the guest memory is the VM's current size
        if (domain?.memory?.maxGuest && domain?.memory?.guest) {
            return CommonParser.parseMemoryValue(domain.memory.guest.toString())
        }
        // Harvester stores the configured memory in resources.limits (guest = limit - reserved overhead)
        if (domain?.resources?.limits?.memory) {
            return CommonParser.parseMemoryValue(domain.resources.limits.memory.toString())
        }
        if (domain?.memory?.guest) {
            // Extract from domain.memory.guest specification (usually in bytes or with units)
            return CommonParser.parseMemoryValue(domain.memory.guest.toString())
        } else if (domain?.resources) {
            // Fallback: try to get from resources
            def resources = domain.resources
            if (resources.requests?.memory) {
                return CommonParser.parseMemoryValue(resources.requests.memory)
            } else if (resources.limits?.memory) {
                return CommonParser.parseMemoryValue(resources.limits.memory)
            }
        }
        return 0L
    }

    static Boolean validateVolume(
            Map vol,
            Map<String, StorageVolumeType> storageVolTypeMap,
            Map<String, StorageControllerType> storageControllerTypeMap,
            String vmName) {

        if (vol.name == HarvesterConstants.CLOUD_INIT_DISK) {
            log.debug("Skipping cloudinitdisk on server: ${vmName}")
            return false
        }
        // CD-ROMs (ISO images) aren't disks in Morpheus: they're managed on the Harvester tab
        if (vol.cdrom == true) {
            log.debug("Skipping CD-ROM ${vol.name} on server: ${vmName}")
            return false
        }

        if (!vol.storageClass) {
            log.warn("Skipping volume: ${vol.name} with no storageClass, server: ${vmName}")
            return false
        }
        def volType = storageVolTypeMap[vol.type]
        if (!volType) {
            log.warn("Skipping volume: ${vol.name} with no supported volType: ${vol.type}, supported volTypes: ${storageVolTypeMap}, server: ${vmName}")
            return false
        }

        def storageControllerType = storageControllerTypeMap[vol.storageController]
        if (!storageControllerType) {
            log.warn("Skipping volume: ${vol.name} with no supported storage cotroller: ${vol.storageController}," +
                    " supported storageController: ${storageControllerTypeMap}, server: ${vmName}")
            return false
        }

        return true
    }

    static filterVolumes(List volumes, String vmName, Map<String, StorageVolumeType> storageVolumeTypeMap, Map<String, StorageControllerType> storageControllerTypeMap) {
        def volumeList = []
        volumes?.each { vol ->
            if (validateVolume(vol, storageVolumeTypeMap, storageControllerTypeMap, vmName)) {
                volumeList << vol
            }
        }
        return volumeList
    }

    /**
     * Extract volume information including storage classes from dataVolumeTemplates and PVCs
     * @param volumes List of volume specifications
     * @param dataVolumeTemplates List of dataVolumeTemplate specifications
     * @param vmNamespace The namespace of the VM
     * @param pvcCache Map of PVC details keyed by namespace:name
     * @param disks List of disk specifications from domain.devices.disks
     * @return List of volume information maps
     */
    static extractVolumeInfo(osType, volumes, dataVolumeTemplates = null, vmNamespace = null, pvcCache = [:], disks = null, dataVolumeCache = [:]) {
        def volumeList = []
        // Create a map of disk configurations for quick lookup by volume name
        Map<String, Object> diskMap = [:]
        def deviceIndexMap = ['scsi':1, 'sata':1, 'virtio':1, 'ide':1] // Start from 'b' for second
        def windowsDeviceIndex = 2 // Start from 2
        disks?.each { disk ->
            if (disk.name) {
                String deviceName
                if (disk.bootOrder && disk.bootOrder == 1) {
                    if (osType?.toLowerCase()?.contains('windows')) {
                        deviceName = "disk 1"
                    } else {
                        deviceName = calculateDeviceName(disk.disk?.bus, 0)
                    }
                } else{
                    if (osType?.toLowerCase()?.contains('windows')) {
                        deviceName = "disk ${windowsDeviceIndex}"
                        windowsDeviceIndex += 1
                    } else{
                        def deviceIndex = deviceIndexMap.get(disk.disk?.bus, 1)
                        deviceName = calculateDeviceName(disk.disk?.bus, deviceIndex)
                        deviceIndexMap[disk.disk?.bus] = deviceIndex + 1
                    }
                }

                diskMap[disk.name] = [
                    bootOrder: disk.bootOrder?:0,
                    bus: disk.disk?.bus ?: disk.cdrom?.bus,
                    deviceName: deviceName,
                    cdrom: disk.cdrom != null
                ]
            }
        }

        // Process regular volumes
        volumes?.each { volume ->
            def volumeInfo = [
                    name: volume.name,
                    type: 'unknown',
                    storageClass: null,
                    sizeBytes: 0L,
                    bootOrder: 0,
                    storageController: null,
                    deviceName: null,
                    namespace: vmNamespace,
                    claimName: null,
                    sourceInfo: [:]
            ]

            // Match with disk configuration if available
            def diskConfig = diskMap[volume.name]
            if (diskConfig) {
                volumeInfo.bootOrder = diskConfig.bootOrder?: 0
                volumeInfo.deviceName = diskConfig.deviceName?: volume.name
                volumeInfo.storageController = "harvester-${diskConfig.bus ?: 'virtio'}"
                volumeInfo.cdrom = diskConfig.cdrom == true
            }

            if (volume.persistentVolumeClaim) {
                volumeInfo.type = HarvesterConstants.VOLUME_TYPE_HARVESTER_PVC // 'persistentVolumeClaim'
                volumeInfo.claimName = volume.persistentVolumeClaim.claimName
                volumeInfo.sourceInfo.type = HarvesterConstants.VOLUME_TYPE_HARVESTER_PVC
                volumeInfo.sourceInfo.name = volume.persistentVolumeClaim.claimName

                // Get storage class and size from PVC cache
                String pvcKey = "${vmNamespace}:${volume.persistentVolumeClaim.claimName}"
                def pvcDetails = pvcCache[pvcKey]
                if (pvcDetails) {
                    volumeInfo.storageClass = pvcDetails.storageClass
                    volumeInfo.sizeBytes = pvcDetails.sizeBytes
                    volumeInfo.sourceInfo.uid = pvcDetails.uid
                } else{
                    log.warn("PVC details not found for volume name: ${volume.name}," +
                            " pvcKey: ${pvcKey}, volume: ${volume}")
                }

            } else if (volume.dataVolume) {
                volumeInfo.type = HarvesterConstants.VOLUME_TYPE_HARVESTER_DATAVOLUME //'dataVolume'
                def dataVolumeName = volume.dataVolume.name
                volumeInfo.dataVolumeName = dataVolumeName
                volumeInfo.sourceInfo.type = HarvesterConstants.VOLUME_TYPE_HARVESTER_DATAVOLUME
                volumeInfo.sourceInfo.name = dataVolumeName

                def dataVolumeKey = "${vmNamespace}:${dataVolumeName}"
                def dataVolumeDetails = dataVolumeCache[dataVolumeKey]
                if (dataVolumeDetails){
                    volumeInfo.sizeBytes = dataVolumeDetails.sizeBytes
                    volumeInfo.storageClass = dataVolumeDetails.storageClass
                    def claimName = dataVolumeDetails.claimName
                    volumeInfo.claimName = claimName
                    volumeInfo.sourceInfo.uid = dataVolumeDetails.uid

                    // update the size from PVC if claimName is available
                    if (claimName) {
                        String pvcKey = "${vmNamespace}:${claimName}"
                        def pvcDetails = pvcCache[pvcKey]
                        if (pvcDetails) {
                            volumeInfo.sizeBytes = pvcDetails.sizeBytes
                        } else {
                            log.warn("PVC details not found for dataVolume: ${dataVolumeName}, claimName: ${claimName}," +
                                    " pvcKey: ${pvcKey}, dataVolumeDetails: ${dataVolumeDetails}")
                        }
                    }
                } else {
                    log.warn("dataVolume with name: ${dataVolumeName} not found for volume: ${volume.name}," +
                            " dataVolumeKey: ${dataVolumeKey}, volume: ${volume}")
                    // now try to get the details from the dataVolumeTemplates if available
                    // this is the case where source is showing as Other
                    dataVolumeTemplates?.each { dvt ->
                        if (dvt.metadata?.name == volume.dataVolume.name) {

                            // first get the size and storage class from the dataVolumeTemplate spec
                            def sizeStr = dvt.spec?.storage?.resources?.requests?.storage
                            if (sizeStr) {
                                volumeInfo.sizeBytes = parseVolumeSize(sizeStr)
                            }
                            volumeInfo.storageClass = dvt.spec?.storage?.storageClassName

                            // now update the exact details  from the PVC if found
                            if (dvt.spec?.sourceRef) {
                                String pvcKey = "${dvt.spec?.sourceRef?.namespace}:${dvt.spec?.sourceRef?.name}"
                                def pvcDetails = pvcCache[pvcKey]
                                if (pvcDetails) {
                                    volumeInfo.storageClass = pvcDetails.storageClass
                                    volumeInfo.sizeBytes = pvcDetails.sizeBytes
                                } else {
                                    log.warn("No PVC details found for volume: ${volume.name}," +
                                            " pvcKey: ${pvcKey}, dataVolumeTemplates: ${dataVolumeTemplates}")
                                }
                            } else if(dvt.spec?.source?.pvc){
                                def pvc = dvt.spec?.source?.pvc
                                String pvcKey = "${pvc?.namespace}:${pvc?.name}"
                                def pvcDetails = pvcCache[pvcKey]
                                if (pvcDetails) {
                                    volumeInfo.storageClass = pvcDetails.storageClass
                                    volumeInfo.sizeBytes = pvcDetails.sizeBytes
                                } else {
                                    log.warn("No PVC details found for volume: ${volume.name}," +
                                            " pvcKey: ${pvcKey}, dataVolumeTemplates: ${dataVolumeTemplates}")
                                }
                            } else if(dvt.spec?.pvc){
                                def pvcDetails = dvt.spec?.pvc   // will not have PVC name
                                if (pvcDetails) {
                                    volumeInfo.storageClass = pvcDetails.storageClassName
                                    sizeStr = pvcDetails?.resources?.requests?.storage
                                    if (sizeStr) {
                                        volumeInfo.sizeBytes = parseVolumeSize(sizeStr)
                                    }
                                } else {
                                    log.warn("No details found for volume: ${volume.name}," +
                                            " dataVolumeTemplates: ${dataVolumeTemplates}")
                                }
                            }
                        }
                    }
                }
            } else if (volume.cloudInitNoCloud) {
                volumeInfo.type = 'cloudInit'
            } else if (volume.emptyDisk) {
                volumeInfo.type = 'emptyDisk'
                def capacityStr = volume.emptyDisk.capacity
                if (capacityStr) {
                    volumeInfo.sizeBytes = parseVolumeSize(capacityStr)
                }
            }

            volumeList << volumeInfo
        }

//        // Process dataVolumeTemplates directly for additional storage information
