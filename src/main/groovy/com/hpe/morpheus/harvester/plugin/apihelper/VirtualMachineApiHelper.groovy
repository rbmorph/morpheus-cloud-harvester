    /**
     * Parse volume size and return in bytes
     * @param sizeStr The size string to parse (e.g., "20Gi", "100Mi")
     * @return Size in bytes
     */
    static parseVolumeSize(String sizeStr) {
        return CommonParser.parseMemoryValue(sizeStr) // Use CommonParser for consistent parsing
    }

    /**
     * Extract OS type from VM template metadata annotations
     * @param templateMetadata The VM template metadata
     * @return String representing the OS type
     */
    static extractOsType(vmName, vmSpec) {
        def osType = 'Unknown'
        def templateMetadata = vmSpec?.template?.metadata
        if (templateMetadata?.annotations) {
            def osAnnotation = templateMetadata.annotations["vm.kubevirt.io/os"]
            if (osAnnotation) {
                osType = osAnnotation.toLowerCase()
            }
        } else if(vmSpec?.preference?.name){
            if (vmSpec.preference.name.toLowerCase().contains('windows')) {
                osType = 'windows'
            } else if (vmSpec.preference.name.toLowerCase().contains('linux')) {
                osType = 'linux'
            }
        }else{
            log.debug("No OS type found for VM: ${vmName}, vm spec: ${vmSpec}")
        }

        return osType
    }

    /**
     * Extract network interfaces from running VM instance
     * @param interfaces List of network interfaces from VM instance status, domain device and networks
     * @return List of interface information maps
     */
    static extractNetworkInterfacesFromSpecAndStatus(interfaces, domainInterfaces, networks) {
        List<Map> result = []
        interfaces?.each { iface ->
            def matchedInterface = domainInterfaces?.find { it.name == iface.name }
            def matchedNetwork = networks?.find { it.name == iface.name }
            def networkName = matchedNetwork?.multus?.networkName ?: (matchedNetwork?.containsKey('pod') ? HarvesterConstants.POD_NETWORK_NAME : null)
            if (networkName) {
                result << [
                        name       : iface.name,
                        macAddress : iface.mac,
                        ipAddress  : iface.ipAddress,
                        ipAddresses: iface.ipAddresses ?: [],
                        model      : matchedInterface?.model,
                        networkName: networkName,
                        defaultPodNetwork: networkName==HarvesterConstants.POD_NETWORK_NAME
                ]
            } else {
                log.warn("No network found for interface: ${iface.name}")
            }
        }
        return result
    }

    /**
     * Extract network interfaces from VM spec (when VM is not running)
     * @param networks List of network specifications
     * @param interfaces List of interface specifications
     * @return List of interface information maps
     */
    static extractNetworkInterfacesFromSpec(networks, interfaces) {
        List<Map> result = []
        interfaces?.each { iface ->
            def matchedNetwork = networks?.find { it.name == iface.name }
            def networkName = matchedNetwork?.multus?.networkName ?: (matchedNetwork?.containsKey('pod') ? HarvesterConstants.POD_NETWORK_NAME : null)
            if (networkName) {
                result << [
                        name: iface.name,
                        macAddress: iface.macAddress,
                        ipAddress: null,
                        ipAddresses: [],
                        model: iface.model,
                        networkName: networkName,
                        defaultPodNetwork: networkName==HarvesterConstants.POD_NETWORK_NAME
                ]
            } else {
                log.warn("No network found for interface: ${iface.name}")
            }
        }
        return result
    }

    /**
     * Calculate device name based on bus type and boot order
     * @param busType The bus type (scsi, sata, virtio, ide)
     * @param bootOrder The boot order (1-based)
     * @return Device name (e.g., sda, vda, hda) or null if bootOrder is 0
     */
    static String calculateDeviceName(String busType, Integer index) {

        char letter = (char) (97 + index)  // 97 is ASCII value of 'a'

        // String letter = String.valueOf((char) ("a".charAt(0) + index))

        // Map bus types to their device name prefixes
        switch (busType?.toLowerCase()) {
            case 'scsi':
                return "/dev/sd${letter}"  // SCSI: sda, sdb, sdc, etc.
            case 'sata':
                return "/dev/sd${letter}"  // SATA: sda, sdb, sdc, etc.
            case 'virtio':
                return "/dev/vd${letter}"  // VirtIO: vda, vdb, vdc, etc.
            case 'ide':
                return "/dev/hd${letter}"  // IDE: hda, hdb, hdc, etc.
            default:
                return "/dev/vd${letter}"  // Default to virtio naming
        }
    }
